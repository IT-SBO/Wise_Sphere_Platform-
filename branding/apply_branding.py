def write_zabbix_assets(tokens: dict) -> None:
    """Build context files for zabbix/web/Dockerfile (needs write_glpi_assets() first for logos and fonts)."""
    ZABBIX_BRAND.mkdir(parents=True, exist_ok=True)
    for f in GLPI_ASSETS.iterdir():
        if f.suffix in (".svg", ".png", ".woff2"):
            (ZABBIX_BRAND / f.name).write_bytes(f.read_bytes())
    sed = ["# GENERATED by branding/apply_branding.py - Zabbix blue theme -> brand colours"]
    for old, new in zabbix_colour_map(tokens):
        sed.append(f"s/{re.sub(r'([][.*^$/\\\\])', r'\\\\\\1', old)}/{new}/gI")  # escape for sed BRE
    (ZABBIX_BRAND / "theme.sed").write_text("\n".join(sed) + "\n")
    c = tokens["colors"]
    values = {**c, "primary_rgb": rgb(c["primary"]), "radius": tokens.get("radius", "6px")}
    css = (HERE / "zabbix-custom.css.tmpl").read_text()
    for k, v in values.items():
        css = css.replace("{{" + k + "}}", str(v))
    missing = sorted(set(re.findall(r"{{(\w+)}}", css)))
    if missing:
        raise SystemExit(f"zabbix-custom.css.tmpl uses unknown tokens: {missing}")
    (ZABBIX_BRAND / "wisesphere.css").write_text(css)
    footer = f"{tokens.get('company_name', tokens['brand_name'])} · {tokens['brand_name']}"
    (ZABBIX_BRAND / "brand.conf.php").write_text(f"""<?php
// GENERATED by branding/apply_branding.py from branding/tokens.json - WiseSphere brand for the Zabbix web UI
return [
\t'BRAND_LOGO' => './assets/img/wisesphere/logo.svg',
\t'BRAND_LOGO_SIDEBAR' => './assets/img/wisesphere/logo-light.svg',
\t'BRAND_LOGO_SIDEBAR_COMPACT' => './assets/img/wisesphere/favicon.png',
\t'BRAND_FOOTER' => {json.dumps(footer, ensure_ascii=False)},
];
""")
    print(f"wrote Zabbix brand files to {ZABBIX_BRAND} (rebuild: docker compose build zabbix-web)")


GRAFANA_BRAND = HERE.parent / "grafana/branding"
GRAFANA_DASHBOARDS = HERE.parent / "grafana/dashboards"


def write_grafana_assets(tokens: dict) -> None:
    """Files mounted into Grafana OSS (it has no custom-CSS or logo setting) + brand colours in the dashboards."""
    GRAFANA_BRAND.mkdir(parents=True, exist_ok=True)
    c = tokens["colors"]
    for f in ("logo.svg", "logo-light.svg", "favicon.png"):
        if (GLPI_ASSETS / f).is_file():
            (GRAFANA_BRAND / f).write_bytes((GLPI_ASSETS / f).read_bytes())
    fav = GRAFANA_BRAND / "favicon.png"
    if fav.is_file():  # Grafana loads its icon as an .svg file: wrap the square brand icon
        b64 = base64.b64encode(fav.read_bytes()).decode()
        (GRAFANA_BRAND / "icon.svg").write_text(
            '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 192 192">'
            f'<image width="192" height="192" xlink:href="data:image/png;base64,{b64}"/></svg>\n')
    (GRAFANA_BRAND / "login-bg.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 900" preserveAspectRatio="xMidYMid slice">'
        '<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{c["text"]}"/><stop offset=".6" stop-color="{c["text"]}" stop-opacity=".92"/>'
        f'<stop offset="1" stop-color="{c["primary"]}"/></linearGradient></defs>'
        f'<rect width="1600" height="900" fill="{c["text"]}"/><rect width="1600" height="900" fill="url(#g)"/></svg>\n')
    # dashboards: threshold / status colours -> brand colours; logo header text panel
    named = {"red": c["danger"], "dark-red": c["danger"], "orange": c["warning"], "green": c["success"],
             "blue": c["primary"], "dark-orange": c["primary_dark"]}
    for dash in sorted(GRAFANA_DASHBOARDS.glob("*.json")):
        d = json.loads(dash.read_text())

        def walk(o):
            if isinstance(o, dict):
                if isinstance(o.get("color"), str) and o["color"] in named:
                    o["color"] = named[o["color"]]
                if isinstance(o.get("fixedColor"), str) and o["fixedColor"] in named:
                    o["fixedColor"] = named[o["fixedColor"]]
                for v in o.values():
                    walk(v)
            elif isinstance(o, list):
                for v in o:
                    walk(v)
        walk(d)
        panels = d.setdefault("panels", [])
        header = next((p for p in panels if p.get("id") == 9000), None)
        html = ('<div style="display:flex;align-items:center;gap:18px;height:100%">'
                '<img src="/public/img/wisesphere/logo.svg" alt="WISE Group" style="height:54px"/>'
                f'<span style="font-size:26px;color:{c["accent"]}">Wise<b style="color:{c["primary"]}">Sphere</b></span>'
                f'<span style="margin-inline-start:auto;color:{c["muted"]};text-transform:uppercase;letter-spacing:.1em;font-weight:700">'
                f'{d.get("title", "").split("–")[-1].strip()}</span></div>')
        if header is None:
            for p in panels:
                p.setdefault("gridPos", {})["y"] = p["gridPos"].get("y", 0) + 3
            header = {"id": 9000, "type": "text", "title": "", "transparent": True,
                      "gridPos": {"h": 3, "w": 24, "x": 0, "y": 0}, "options": {"mode": "html", "content": ""}}
            panels.insert(0, header)
        header["options"]["content"] = html
        dash.write_text(json.dumps(d, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote Grafana brand files to {GRAFANA_BRAND} and brand colours to {GRAFANA_DASHBOARDS}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tokens", default=str(HERE / "tokens.json"))
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--glpi-url")
    ap.add_argument("--admin-user", default="glpi")
    ap.add_argument("--admin-password")
    ap.add_argument("--app-token", help="GLPI API client app token, if the client used requires one")
    a = ap.parse_args()
    tokens = json.loads(Path(a.tokens).read_text())
    css = render(tokens)
    out = HERE / "build"
    out.mkdir(exist_ok=True)
    (out / "glpi-custom.css").write_text(css)
    print(f"rendered {out / 'glpi-custom.css'} ({len(css)} bytes)")
    portal_tokens = HERE.parent / "web/portal/src/tokens.css"
    portal_tokens.write_text(render_portal_tokens(tokens))
    print(f"rendered {portal_tokens}")
    # logo + favicon as files for the portal (<img>, <link rel=icon>)
    public = HERE.parent / "web/portal/public/brand"
    public.mkdir(parents=True, exist_ok=True)
    for key, name in (("logo", "logo"), ("favicon", "favicon")):
        src = HERE / tokens.get(key, "")
        if tokens.get(key) and src.is_file():
            (public / f"{name}{src.suffix}").write_bytes(src.read_bytes())
            print(f"copied {src.name} -> {public / (name + src.suffix)}")
    write_glpi_assets(tokens)
    write_zabbix_assets(tokens)
    write_grafana_assets(tokens)
    if a.render or not a.glpi_url:
        return 0
    from provision_glpi import Glpi  # noqa: E402
    g = Glpi(a.glpi_url, a.admin_user, a.admin_password, a.app_token)
    try:
        g.call("PUT", "/Entity/0", {"input": {"enable_custom_css": 1, "custom_css_code": css}})
        # client entities inherit (-2 = inherit from parent)
        for e in g.call("GET", "/Entity", params={"range": "0-500"}) or []:
            if int(e["id"]) != 0 and str(e.get("enable_custom_css")) not in ("-2",):
                g.call("PUT", f"/Entity/{e['id']}", {"input": {"enable_custom_css": -2}})
    finally:
        g.close()
    print("GLPI: brand CSS applied to the root entity (inherited by client entities)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
