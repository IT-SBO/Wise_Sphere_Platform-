#!/usr/bin/env python3
"""Render the n8n env file (non-secret WS_* settings) from a base file, GLPI ids and tenants.yaml.

  render_n8n_env.py --ids lab/glpi-ids.json --base lab/n8n.env.base --out lab/n8n.env

WS_TENANTS_JSON carries tier + country per client code for WF-04 (tier-aware SLA SMS).
Restart n8n after changing it (SOP-01 step "register client in n8n").
"""
import argparse
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

ap = argparse.ArgumentParser()
ap.add_argument("--ids", required=True)
ap.add_argument("--base", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--tenants", default=str(ROOT / "config/tenants.yaml"))
a = ap.parse_args()

ids = json.loads(Path(a.ids).read_text())
tenants = yaml.safe_load(Path(a.tenants).read_text())
values = {
    "WS_GLPI_DEFAULT_ENTITY": 0,
    "WS_GLPI_REQTYPE_MONITORING": ids["requesttypes"]["monitoring"],
    "WS_GLPI_REQTYPE_SECURITY": ids["requesttypes"]["security"],
    "WS_GLPI_GROUP_NOC": ids["groups"]["noc"],
    "WS_GLPI_GROUP_SOC": ids["groups"]["soc"],
    "WS_GLPI_GROUP_SDM": ids["groups"]["sdm"],
    "WS_GLPI_SOLUTIONTYPE": ids["solutiontype"],
    "WS_TENANTS_JSON": json.dumps({t["code"]: {"tier": t["tier"], "country": t["country"]} for t in tenants["tenants"]},
                                  separators=(",", ":")),
}
lines = [l for l in Path(a.base).read_text().splitlines() if l.split("=", 1)[0] not in values]
lines += ["", "# ---- generated by scripts/render_n8n_env.py ----"] + [f"{k}={v}" for k, v in values.items()]
Path(a.out).write_text("\n".join(lines) + "\n")
print(f"wrote {a.out}")
