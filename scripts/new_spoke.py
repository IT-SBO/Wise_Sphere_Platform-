#!/usr/bin/env python3
"""Prepare a new client site (SOP-01 steps 1-3) - run on the hub.

  new_spoke.py CL001 KWI --hub-endpoint hub.example.com:51820 --hub-pubkey <hub wg public key> \
      --zabbix-url https://zabbix.internal.example.com/api_jsonrpc.php --zabbix-user Admin --zabbix-password ...

Does three things:
  1. generates the spoke WireGuard key pair and the Zabbix proxy PSK (unique per site, NFR-SEC-03)
  2. registers the active proxy CLnnn-SITE-PRX01 with PSK encryption in Zabbix
  3. writes bundles/<CL>-<SITE>/ {spoke.env, wg0.conf, proxy.psk, hub-peer.conf}
     -> copy the bundle to the spoke VM (vault / secure channel) and run spoke/install-spoke.sh
     -> append hub-peer.conf to /etc/wireguard/wg0.conf on the hub and `wg syncconf`
The bundle contains secrets: store it in the vault collection of the client, then delete it.
"""
from __future__ import annotations

import argparse
import base64
import ipaddress
import os
import secrets
import sys
from pathlib import Path

import yaml
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "zabbix"))


def wg_keypair() -> tuple[str, str]:
    k = X25519PrivateKey.generate()
    priv = k.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw, serialization.NoEncryption())
    pub = k.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    return base64.b64encode(priv).decode(), base64.b64encode(pub).decode()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("client")
    ap.add_argument("site")
    ap.add_argument("--hub-endpoint", required=True)
    ap.add_argument("--hub-pubkey", required=True)
    ap.add_argument("--hub-ip", default="10.250.0.1")
    ap.add_argument("--wazuh-manager-ip", default="10.250.0.13")
    ap.add_argument("--glpi-url", default=os.environ.get("WS_GLPI_PUBLIC_URL", "https://support.example.com/"))
    ap.add_argument("--zabbix-url")
    ap.add_argument("--zabbix-user", default="Admin")
    ap.add_argument("--zabbix-password", default=os.environ.get("ZABBIX_ADMIN_PASSWORD"))
    ap.add_argument("--tenants", default=str(ROOT / "config/tenants.yaml"))
    ap.add_argument("--out", default=str(ROOT / "bundles"))
    a = ap.parse_args()

    tenants = yaml.safe_load(Path(a.tenants).read_text())
    t = next((t for t in tenants["tenants"] if t["code"] == a.client), None)
    if not t:
        sys.exit(f"{a.client} is not in {a.tenants} - add the client there first")
    site = next((s for s in t.get("sites", []) if s["code"] == a.site), None)
    if not site:
        sys.exit(f"site {a.site} is not defined for {a.client}")
    net = ipaddress.ip_network(site["wg_subnet"])
    spoke_ip = next(net.hosts())
    proxy = f"{a.client}-{a.site}-PRX01"
    psk_identity = f"{proxy}-psk"
    psk = secrets.token_hex(32)  # 256-bit PSK
    priv, pub = wg_keypair()

    out = Path(a.out) / f"{a.client}-{a.site}"
    out.mkdir(parents=True, exist_ok=True)
    os.chmod(out, 0o700)

    def write(name: str, text: str):
        p = out / name
        p.write_text(text)
        os.chmod(p, 0o600)

    write("proxy.psk", psk + "\n")
    write("wg0.conf", f"""[Interface]
# {a.client} {a.site} spoke - outbound only
PrivateKey = {priv}
Address = {spoke_ip}/{net.prefixlen}

[Peer]
# WiseSphere hub
PublicKey = {a.hub_pubkey}
Endpoint = {a.hub_endpoint}
AllowedIPs = {a.hub_ip}/32, {a.wazuh_manager_ip}/32
PersistentKeepalive = 25
""")
    write("hub-peer.conf", f"""
[Peer]
# {a.client.lower()}-{a.site.lower()}
PublicKey = {pub}
AllowedIPs = {net}
""")
    write("spoke.env", f"""CLIENT_CODE={a.client}
SITE_CODE={a.site}
PROXY_NAME={proxy}
PROXY_PSK_IDENTITY={psk_identity}
ZABBIX_TAG=alpine-8.0.0
NGINX_TAG=1.30.7-alpine
GLPI_AGENT_VERSION=1.18
GLPI_SERVER_URL={a.glpi_url}
WG_HUB_IP={a.hub_ip}
WAZUH_MANAGER_IP={a.wazuh_manager_ip}
ENABLE_WAZUH_RELAY=false
# ---- fill in on site (SOP-01 data pack)
SPOKE_LAN_IP=
CLIENT_LAN=
ADMIN_CIDR=
""")

    if a.zabbix_url:
        from provision_zabbix import Zbx  # noqa: E402
        z = Zbx(a.zabbix_url, a.zabbix_user, a.zabbix_password)
        body = {"name": proxy, "operating_mode": 0, "tls_accept": 2, "tls_psk_identity": psk_identity, "tls_psk": psk,
                "description": f"{t['name']} / {a.site} - generated by scripts/new_spoke.py"}
        found = z.call("proxy.get", {"filter": {"name": [proxy]}, "output": ["proxyid"]})
        if found:
            z.call("proxy.update", {"proxyid": found[0]["proxyid"], **{k: v for k, v in body.items() if k != "name"}})
        else:
            z.call("proxy.create", body)
        print(f"Zabbix proxy {proxy} registered (active, PSK)")
    print(f"bundle written to {out} - contains secrets, move it to the vault")
    return 0


if __name__ == "__main__":
    sys.exit(main())
