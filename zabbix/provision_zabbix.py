#!/usr/bin/env python3
"""Provision Zabbix 8.0 for WiseSphere through the JSON-RPC API (idempotent).

From config/tenants.yaml it creates or updates:
  * host groups  CLnnn/SITE/Network, CLnnn/SITE/Servers, WiseSphere/Hub        NOC-01, §4.7
  * global macro {$WS_ZABBIX_URL} (deep link written into tickets)
  * media type  "WiseSphere" (webhook, ws.event.v1, secret header, retries) INT-01, INT-05
  * user group "WS Notify" (read on all WiseSphere groups) + user svc-ws-notify with that media
  * trigger action "WiseSphere: open GLPI ticket" - problem, recovery and update operations,
    skips suppressed problems (maintenance windows, NOC-04) and severities below Warning (K-03)
  * --lab: host cl001-kwi-lab with 15 trapper-driven test triggers (TC-01..TC-04, TC-09)
           and the agent host cl001-kwi-srv01 (PoC "agent not available" test)

  provision_zabbix.py --url http://localhost:8081/api_jsonrpc.php --user Admin --password zabbix \
      --webhook-url http://ws-integration:8080/webhook/zbx-event --webhook-secret ... [--lab]
"""
from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

import requests
import yaml

ROOT = Path(__file__).resolve().parent.parent
MEDIA_NAME = "WiseSphere"
ACTION_NAME = "WiseSphere: open GLPI ticket"
SCRIPT = (ROOT / "zabbix/mediatype-script.js").read_text()

PARAMS = [
    ("url", "{$WS_WEBHOOK_URL}"),
    ("secret", "{$WS_WEBHOOK_SECRET}"),
    ("event_id", "{EVENT.ID}"),
    ("event_value", "{EVENT.VALUE}"),
    ("event_update", "{EVENT.UPDATE.STATUS}"),
    ("severity", "{EVENT.NSEVERITY}"),
    ("event_name", "{EVENT.NAME}"),
    ("host", "{HOST.HOST}"),
    ("host_name", "{HOST.NAME}"),
    ("host_ip", "{HOST.IP}"),
    ("tags", "{EVENT.TAGSJSON}"),
    ("event_time", "{EVENT.DATE} {EVENT.TIME}"),
    ("opdata", "{EVENT.OPDATA}"),
    ("trigger_id", "{TRIGGER.ID}"),
    ("update_message", "{EVENT.UPDATE.MESSAGE}"),
    ("update_user", "{USER.FULLNAME}"),
    ("event_url", "{$WS_ZABBIX_URL}/tr_events.php?triggerid={TRIGGER.ID}&eventid={EVENT.ID}"),
    ("HTTPProxy", ""),
]


# Read-only API methods for the portal and Grafana (role "WS API read-only")
READONLY_API_METHODS = ["hostgroup.get", "host.get", "problem.get", "event.get", "trigger.get", "item.get",
                        "history.get", "trend.get", "service.get", "sla.get", "sla.getsli", "proxy.get"]


class Zbx:
    def __init__(self, url: str, user: str, password: str):
        self.url, self.n = url, 0
        self.s = requests.Session()
        token = self.call("user.login", {"username": user, "password": password}, auth=False)
        self.s.headers["Authorization"] = f"Bearer {token}"

    def call(self, method: str, params, auth=True):
        self.n += 1
        r = self.s.post(self.url, json={"jsonrpc": "2.0", "method": method, "params": params, "id": self.n},
                        headers={"Content-Type": "application/json-rpc"}, timeout=30)
        r.raise_for_status()
        d = r.json()
        if "error" in d:
            raise RuntimeError(f"{method}: {d['error'].get('data') or d['error']}")
        return d["result"]


def ensure_group(z: Zbx, name: str) -> str:
    g = z.call("hostgroup.get", {"filter": {"name": [name]}, "output": ["groupid"]})
    return g[0]["groupid"] if g else z.call("hostgroup.create", {"name": name})["groupids"][0]


def ensure_macro(z: Zbx, macro: str, value: str, secret=False):
    m = z.call("usermacro.get", {"globalmacro": True, "filter": {"macro": macro}, "output": ["globalmacroid"]})
    body = {"macro": macro, "value": value, "type": 1 if secret else 0}
    if m:
        z.call("usermacro.updateglobal", {"globalmacroid": m[0]["globalmacroid"], "value": value, "type": body["type"]})
    else:
        z.call("usermacro.createglobal", body)


def ensure_mediatype(z: Zbx) -> str:
    tmpl = [
        {"eventsource": 0, "recovery": 0, "subject": "Problem: {EVENT.NAME}", "message": "Problem {EVENT.ID} on {HOST.NAME}: {EVENT.NAME}"},
        {"eventsource": 0, "recovery": 1, "subject": "Resolved: {EVENT.NAME}", "message": "Resolved {EVENT.ID} on {HOST.NAME}: {EVENT.NAME}"},
        {"eventsource": 0, "recovery": 2, "subject": "Updated: {EVENT.NAME}", "message": "{USER.FULLNAME} {EVENT.UPDATE.ACTION} {EVENT.ID}: {EVENT.UPDATE.MESSAGE}"},
    ]
    body = {
        "name": MEDIA_NAME, "type": 4, "status": 0, "script": SCRIPT, "timeout": "30s",
        "process_tags": 0, "show_event_menu": 0, "maxattempts": 3, "attempt_interval": "10s",
        # Parallel delivery: the integration service serialises per client (dedupe/storm stay race-free)
        # and processes different clients concurrently.
        "maxsessions": 10,
        "description": "WiseSphere INT-01: sends ws.event.v1 to the integration service. Generated by zabbix/provision_zabbix.py.",
        "parameters": [{"name": k, "value": v} for k, v in PARAMS],
        "message_templates": tmpl,
    }
    m = z.call("mediatype.get", {"filter": {"name": [MEDIA_NAME]}, "output": ["mediatypeid"]})
    if m:
        z.call("mediatype.update", {"mediatypeid": m[0]["mediatypeid"], **body})
        return m[0]["mediatypeid"]
    return z.call("mediatype.create", body)["mediatypeids"][0]


def ensure_notify_user(z: Zbx, mediatype_id: str, group_ids: list[str]) -> str:
    rights = [{"id": g, "permission": 2} for g in group_ids]
    ug = z.call("usergroup.get", {"filter": {"name": ["WS Notify"]}, "output": ["usrgrpid"]})
    if ug:
        ugid = ug[0]["usrgrpid"]
        z.call("usergroup.update", {"usrgrpid": ugid, "hostgroup_rights": rights})
    else:
        ugid = z.call("usergroup.create", {"name": "WS Notify", "gui_access": 3, "hostgroup_rights": rights})["usrgrpids"][0]
    media = [{"mediatypeid": mediatype_id, "sendto": "integration", "active": 0, "severity": 63, "period": "1-7,00:00-24:00"}]
    u = z.call("user.get", {"filter": {"username": ["svc-ws-notify"]}, "output": ["userid"]})
    if u:
        z.call("user.update", {"userid": u[0]["userid"], "usrgrps": [{"usrgrpid": ugid}], "medias": media})
        return u[0]["userid"]
    role = z.call("role.get", {"filter": {"name": ["User role"]}, "output": ["roleid"]})
    return z.call("user.create", {
        "username": "svc-ws-notify", "name": "WiseSphere", "surname": "Notifications",
        "passwd": secrets.token_urlsafe(24) + "Aa1!", "roleid": role[0]["roleid"],
        "usrgrps": [{"usrgrpid": ugid}], "medias": media,
    })["userids"][0]


def ensure_readonly_token(z: Zbx, group_ids: list[str], username: str, token_name: str) -> str:
    """Read-only API user + token (portal, Grafana). Regenerates the token on every run - store it in the vault."""
    rights = [{"id": g, "permission": 2} for g in group_ids]
    ug = z.call("usergroup.get", {"filter": {"name": ["WS Read-only API"]}, "output": ["usrgrpid"]})
    if ug:
        ugid = ug[0]["usrgrpid"]
        z.call("usergroup.update", {"usrgrpid": ugid, "hostgroup_rights": rights})
    else:
        ugid = z.call("usergroup.create", {"name": "WS Read-only API", "gui_access": 3, "hostgroup_rights": rights})["usrgrpids"][0]
    # Zabbix 8.0's default "User role" has API access off: use a dedicated role allowing read methods only
    rules = {"api.access": 1, "api.mode": 1, "api": READONLY_API_METHODS, "ui.default_access": 0, "modules.default_access": 0,
             "actions.default_access": 0}
    role = z.call("role.get", {"filter": {"name": ["WS API read-only"]}, "output": ["roleid"]})
    if role:
        roleid = role[0]["roleid"]
        z.call("role.update", {"roleid": roleid, "rules": rules})
    else:
        roleid = z.call("role.create", {"name": "WS API read-only", "type": 1, "rules": rules})["roleids"][0]
    u = z.call("user.get", {"filter": {"username": [username]}, "output": ["userid"]})
    if u:
        uid = u[0]["userid"]
        z.call("user.update", {"userid": uid, "roleid": roleid, "usrgrps": [{"usrgrpid": ugid}]})
    else:
        uid = z.call("user.create", {"username": username, "passwd": secrets.token_urlsafe(24) + "Aa1!",
                                     "roleid": roleid, "usrgrps": [{"usrgrpid": ugid}]})["userids"][0]
    old = z.call("token.get", {"userids": [uid], "filter": {"name": token_name}, "output": ["tokenid"]})
    if old:
        z.call("token.delete", [t["tokenid"] for t in old])
    tid = z.call("token.create", {"name": token_name, "userid": uid})["tokenids"][0]
    return z.call("token.generate", [tid])[0]["token"]


def ensure_action(z: Zbx, mediatype_id: str, user_id: str) -> str:
    body = {
        "name": ACTION_NAME, "eventsource": 0, "status": 0, "esc_period": "1h",
        "filter": {"evaltype": 1, "conditions": [
            {"conditiontype": 16, "operator": 11},              # problem is not suppressed (maintenance)
            {"conditiontype": 4, "operator": 5, "value": "2"},  # trigger severity >= Warning
        ]},
        "operations": [{"operationtype": 0, "esc_step_from": 1, "esc_step_to": 1,
                        "opmessage": {"default_msg": 1, "mediatypeid": mediatype_id},
                        "opmessage_usr": [{"userid": user_id}]}],
        "recovery_operations": [{"operationtype": 11, "opmessage": {"default_msg": 1}}],
        "update_operations": [{"operationtype": 12, "opmessage": {"default_msg": 1}}],
    }
    a = z.call("action.get", {"filter": {"name": [ACTION_NAME]}, "output": ["actionid"]})
    if a:
        z.call("action.update", {"actionid": a[0]["actionid"], **{k: v for k, v in body.items() if k != "eventsource"}})
        return a[0]["actionid"]
    return z.call("action.create", body)["actionids"][0]


def ensure_host(z: Zbx, host: str, name: str, group_id: str, tags: dict, interfaces=None, templates=None) -> str:
    h = z.call("host.get", {"filter": {"host": [host]}, "output": ["hostid"]})
    body = {"host": host, "name": name, "groups": [{"groupid": group_id}],
            "tags": [{"tag": k, "value": v} for k, v in tags.items()]}
    if templates:
        body["templates"] = [{"templateid": t} for t in templates]
    if h:
        z.call("host.update", {"hostid": h[0]["hostid"], **body})
        return h[0]["hostid"]
    if interfaces:
        body["interfaces"] = interfaces
    return z.call("host.create", body)["hostids"][0]


def ensure_lab(z: Zbx, groups: dict) -> dict:
    """Lab hosts: 15 trapper 'devices' for fast deterministic tests + one real agent."""
    gid = groups["CL001/KWI/Servers"]
    tags = {"client": "CL001", "site": "KWI"}
    hid = ensure_host(z, "cl001-kwi-lab", "CL001 KWI lab devices", gid, tags)
    for n in range(1, 16):
        key = f"ws.test.{n}"
        it = z.call("item.get", {"hostids": hid, "filter": {"key_": key}, "output": ["itemid"]})
        if not it:
            z.call("item.create", {"hostid": hid, "name": f"Lab device {n} state", "key_": key, "type": 2, "value_type": 3,
                                   "history": "7d", "trends": "0"})
        desc = f"Lab device {n:02d} is down"
        tr = z.call("trigger.get", {"hostids": hid, "filter": {"description": desc}, "output": ["triggerid"]})
        if not tr:
            z.call("trigger.create", {"description": desc, "expression": f"last(/cl001-kwi-lab/{key})=1",
                                      "recovery_mode": 0, "priority": 4, "manual_close": 1})
    tmpl = z.call("template.get", {"filter": {"host": ["Linux by Zabbix agent"]}, "output": ["templateid"]})
    agent = ensure_host(z, "cl001-kwi-srv01", "CL001 KWI srv01 (agent)", gid, tags,
                        interfaces=[{"type": 1, "main": 1, "useip": 0, "ip": "", "dns": "lab-device-01", "port": "10050"}],
                        templates=[tmpl[0]["templateid"]] if tmpl else None)
    return {"trapper_host": hid, "agent_host": agent}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--url", required=True)
    ap.add_argument("--user", default=os.environ.get("ZABBIX_ADMIN_USER", "Admin"))
    ap.add_argument("--password", default=os.environ.get("ZABBIX_ADMIN_PASSWORD"))
    ap.add_argument("--webhook-url", default=os.environ.get("WS_ZBX_WEBHOOK_URL", "http://ws-integration:8080/webhook/zbx-event"))
    ap.add_argument("--webhook-secret", default=os.environ.get("WS_WEBHOOK_SECRET"))
    ap.add_argument("--zabbix-public-url", default=os.environ.get("WS_ZABBIX_PUBLIC_URL", "http://localhost:8081"))
    ap.add_argument("--tenants", default=str(ROOT / "config/tenants.yaml"))
    ap.add_argument("--lab", action="store_true", help="also create lab test hosts")
    ap.add_argument("--readonly-token-out", help="create a read-only API token (portal/Grafana) and write it to this file (mode 600)")
    args = ap.parse_args()
    if not args.password or not args.webhook_secret:
        ap.error("--password and --webhook-secret are required (or ZABBIX_ADMIN_PASSWORD / WS_WEBHOOK_SECRET)")

    tenants = yaml.safe_load(Path(args.tenants).read_text())
    z = Zbx(args.url, args.user, args.password)
    groups = {"WiseSphere/Hub": ensure_group(z, "WiseSphere/Hub")}
    for t in tenants["tenants"]:
        for site in t.get("sites", []):
            for kind in ("Network", "Servers"):
                name = f"{t['code']}/{site['code']}/{kind}"
                groups[name] = ensure_group(z, name)
    ensure_macro(z, "{$WS_WEBHOOK_URL}", args.webhook_url)
    ensure_macro(z, "{$WS_WEBHOOK_SECRET}", args.webhook_secret, secret=True)
    ensure_macro(z, "{$WS_ZABBIX_URL}", args.zabbix_public_url.rstrip("/"))
    mt = ensure_mediatype(z)
    uid = ensure_notify_user(z, mt, list(groups.values()))
    act = ensure_action(z, mt, uid)
    out = {"groups": groups, "mediatype": mt, "notify_user": uid, "action": act}
    if args.lab:
        out["lab"] = ensure_lab(z, groups)
    if args.readonly_token_out:
        token = ensure_readonly_token(z, [g for n, g in groups.items() if n.startswith("CL")], "svc-ws-readonly", "wisesphere-portal")
        Path(args.readonly_token_out).write_text(token + "\n")
        os.chmod(args.readonly_token_out, 0o600)
        out["readonly_token"] = args.readonly_token_out
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
